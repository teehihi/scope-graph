const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    return (localStorage.getItem('scopegraph_lang') as Language) || 'vi';
  });

  const [translateWithMeta, setTranslateWithMetaState] = useState<boolean>(() => {
    return localStorage.getItem('scopegraph_meta_translate') === 'true';
  });

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem('scopegraph_lang', lang);
  };

  const setTranslateWithMeta = (val: boolean) => {
    setTranslateWithMetaState(val);
    localStorage.setItem('scopegraph_meta_translate', val ? 'true' : 'false');
  };

  const t = (key: string): string => {
    return DICTIONARY[language]?.[key] || DICTIONARY.en[key] || key;
  };

  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage,
        translateWithMeta,
        setTranslateWithMeta,
        t,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = (): LanguageContextType => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
